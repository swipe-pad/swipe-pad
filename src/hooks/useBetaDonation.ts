'use client'

import { useState, useCallback } from 'react'
import { useActiveAccount, useSendTransaction } from 'thirdweb/react'
import { getContract, prepareContractCall } from 'thirdweb'
import { client } from '@/lib/thirdweb-client'
import { celo, base } from 'thirdweb/chains'
import { betaDonationPoolAbi, BETA_POOL_ADDRESS } from '@/types/contracts'
import { buildBatchDonationParams } from '@/lib/beta-donation-batch'
import type { Project } from '@/lib/useConvexData'

export interface DonationItem {
  project: Project
  amount: number // In dollars (e.g., 0.01)
}

export interface UseBetaDonationResult {
  donate: (items: DonationItem[]) => Promise<string | null>
  isLoading: boolean
  error: Error | null
  txHash: string | null
  /** True when an on-chain donation can actually be attempted (wallet + deployed pool) */
  canDonateOnchain: boolean
}

/**
 * Hook to execute batch donations via the BetaDonationPool contract
 * No token approval needed - pool already has the tokens
 */
export function useBetaDonation(chain: 'celo' | 'base' = 'celo'): UseBetaDonationResult {
  const account = useActiveAccount()
  const { mutateAsync: sendTransaction } = useSendTransaction()

  const [isLoading, setIsLoading] = useState(false)
  const [error, setError] = useState<Error | null>(null)
  const [txHash, setTxHash] = useState<string | null>(null)

  // src/types/contracts.ts is regenerated by `bun run wagmi:generate` (wagmi-cli.config.ts
  // targets it directly), so the hardcoded zero-address placeholders there get clobbered on
  // every regen. Env overrides let ops set the real address post-deploy without touching
  // generated code or waiting on a manual re-edit.
  const envOverride = (
    chain === 'celo'
      ? process.env.NEXT_PUBLIC_BETA_POOL_ADDRESS_CELO
      : process.env.NEXT_PUBLIC_BETA_POOL_ADDRESS_BASE
  ) as `0x${string}` | undefined
  const poolAddress = (envOverride || BETA_POOL_ADDRESS[chain]) as `0x${string}`
  const chainConfig = chain === 'celo' ? celo : base

  const isPoolDeployed = poolAddress !== '0x0000000000000000000000000000000000000000'

  const donate = useCallback(
    async (items: DonationItem[]): Promise<string | null> => {
      if (!account?.address) {
        setError(new Error('Wallet not connected'))
        return null
      }

      if (!isPoolDeployed) {
        setError(new Error('Beta donation pool not deployed'))
        return null
      }

      setIsLoading(true)
      setError(null)
      setTxHash(null)

      try {
        const contract = getContract({
          client,
          chain: chainConfig,
          address: poolAddress,
          abi: betaDonationPoolAbi,
        })

        // Convert items to contract format (recipients + wei amounts, precision-safe)
        const { recipients, amounts } = buildBatchDonationParams(items)

        // Prepare the batchDonate call
        const tx = prepareContractCall({
          contract,
          method: 'batchDonate',
          params: [recipients, amounts],
        })

        // Execute
        const result = await sendTransaction(tx)
        const hash = result.transactionHash

        setTxHash(hash)
        return hash
      } catch (err) {
        console.error('Donation failed:', err)
        setError(err instanceof Error ? err : new Error(String(err)))
        return null
      } finally {
        setIsLoading(false)
      }
    },
    [account, chainConfig, poolAddress, isPoolDeployed, sendTransaction]
  )

  return {
    donate,
    isLoading,
    error,
    txHash,
    canDonateOnchain: Boolean(account?.address) && isPoolDeployed,
  }
}
